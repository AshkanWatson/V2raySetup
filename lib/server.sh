#!/usr/bin/env bash
# server.sh — firewall and server tuning (BBR, swap, limits, fail2ban).

# ------------------------------------------------------------- firewall ---
fw_detect() {
  if has ufw; then FW=ufw
  elif has firewall-cmd; then FW=firewalld
  elif [[ $PKG == apt ]]; then FW=ufw
  elif [[ $PKG == dnf || $PKG == yum ]]; then FW=firewalld
  else FW=iptables; fi
}

fw_install() {
  case $FW in
    ufw) has ufw || pkg_install ufw ;;
    firewalld) { has firewall-cmd || pkg_install firewalld; } && run systemctl enable --now firewalld ;;
    iptables) has iptables || pkg_install iptables ;;
  esac
}

# fw_allow PORT... — opens tcp+udp. SSH is always opened before enabling.
fw_allow() {
  local p
  for p in "$@"; do
    case $FW in
      ufw) run ufw allow "$p/tcp"; run ufw allow "$p/udp" ;;
      firewalld) run firewall-cmd --permanent --add-port="$p/tcp"; run firewall-cmd --permanent --add-port="$p/udp" ;;
      iptables)
        local proto
        for proto in tcp udp; do
          iptables -C INPUT -p $proto --dport "$p" -j ACCEPT 2>/dev/null || run iptables -I INPUT -p $proto --dport "$p" -j ACCEPT
        done ;;
    esac
  done
}

fw_enable() {
  case $FW in
    ufw) run ufw default deny incoming; run ufw default allow outgoing; run ufw --force enable ;;
    firewalld) run firewall-cmd --reload ;;
    iptables) : ;;
  esac
}

# fw_setup PORT... — install, allow SSH + given ports, enable
fw_setup() {
  fw_install || return 1
  fw_allow "$SSH_PORT" "$@" || return 1
  fw_enable
}

fw_status() {
  case $FW in
    ufw) ufw status 2>/dev/null | head -n 30 ;;
    firewalld) firewall-cmd --list-ports 2>/dev/null ;;
    iptables) iptables -S INPUT 2>/dev/null | head -n 30 ;;
  esac
}

# ports a panel process is actually listening on (after install)
detect_panel_ports() {
  ss -ltnpH 2>/dev/null | awk '/x-ui|xray|sing-box|s-ui|h-ui|hysteria|uvicorn|python|marz|pasarguard|npanel|Npanel/ {n=split($4,a,":"); print a[n]}' \
    | grep -E '^[0-9]+$' | sort -un | tr '\n' ' '
}

# ------------------------------------------------------------- tuning ---
bbr_enabled() { [[ "$(sysctl -n net.ipv4.tcp_congestion_control 2>/dev/null)" == bbr ]]; }

enable_bbr() {
  if [[ $VIRT == openvz || $VIRT == lxc ]]; then ui_warn "BBR can't be changed inside $VIRT containers — skipped"; return 0; fi
  if ! version_ge "${KERNEL%%-*}" 4.9; then ui_warn "Kernel $KERNEL is older than 4.9 — BBR not available"; return 0; fi
  if bbr_enabled; then ui_ok "BBR already enabled"; return 0; fi
  write_file /etc/sysctl.d/99-v2raysetup.conf 644 <<'EOF'
# generated by V2raySetup
net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr
net.ipv4.tcp_fastopen = 3
net.ipv4.tcp_mtu_probing = 1
net.core.rmem_max = 16777216
net.core.wmem_max = 16777216
net.ipv4.tcp_rmem = 4096 87380 16777216
net.ipv4.tcp_wmem = 4096 65536 16777216
net.ipv4.ip_local_port_range = 1024 65535
net.core.somaxconn = 4096
fs.file-max = 1048576
EOF
  ui_spin "Applying BBR + network tuning" sysctl --system
}

create_swap() { # size in MB
  local mb=$1
  if (( SWAP_MB > 0 )); then ui_ok "Swap already present (${SWAP_MB}MB)"; return 0; fi
  if [[ $VIRT == openvz || $VIRT == lxc ]]; then ui_warn "Swap can't be created in $VIRT containers — skipped"; return 0; fi
  ui_spin "Creating ${mb}MB swap file" bash -c "
    (fallocate -l ${mb}M /swapfile 2>/dev/null || dd if=/dev/zero of=/swapfile bs=1M count=$mb) &&
    chmod 600 /swapfile && mkswap /swapfile && swapon /swapfile &&
    { grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab; }" || return 1
  SWAP_MB=$mb
}

raise_limits() {
  write_file /etc/security/limits.d/99-v2raysetup.conf 644 <<'EOF'
# generated by V2raySetup
* soft nofile 1048576
* hard nofile 1048576
root soft nofile 1048576
root hard nofile 1048576
EOF
  [[ -d /etc/systemd ]] && write_file /etc/systemd/system.conf.d/99-v2raysetup.conf 644 <<'EOF'
[Manager]
DefaultLimitNOFILE=1048576
EOF
  ui_ok "Raised open-file limits to 1048576"
}

install_fail2ban() {
  ui_spin "Installing fail2ban" pkg_install fail2ban || return 1
  write_file /etc/fail2ban/jail.d/v2raysetup.local 644 <<EOF
# generated by V2raySetup
[sshd]
enabled  = true
port     = $SSH_PORT
maxretry = 5
findtime = 10m
bantime  = 1h
EOF
  ui_spin "Starting fail2ban" systemctl enable --now fail2ban && svc_restart fail2ban
}

set_timezone() { has timedatectl && ui_spin "Setting timezone to $1" timedatectl set-timezone "$1"; }
